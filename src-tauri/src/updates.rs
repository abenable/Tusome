    // 4. compute_pack_sha256 determinism + sensitivity.
    #[test]
    fn pack_sha256_determinism_and_sensitivity() {
        let a = TempDir::new().unwrap();
        let a_dir = a.path().join("pack");
        write_pack_files(
            &a_dir,
            &[("pack.json", b"hello"), ("img.png", b"image-bytes")],
        );
        let h1 = compute_pack_sha256(&a_dir).unwrap();

        // Same contents → same hash.
        let b = TempDir::new().unwrap();
        let b_dir = b.path().join("pack");
        write_pack_files(
            &b_dir,
            &[("pack.json", b"hello"), ("img.png", b"image-bytes")],
        );
        let h2 = compute_pack_sha256(&b_dir).unwrap();
        assert_eq!(h1, h2, "identical dirs must hash identically");

        // Change one byte in any file → different hash.
        fs::write(b_dir.join("pack.json"), b"helloX").unwrap();
        let h3 = compute_pack_sha256(&b_dir).unwrap();
        assert_ne!(h1, h3, "a single byte change must change the hash");

        // Change one byte in an image file → different hash.
        fs::write(b_dir.join("pack.json"), b"hello").unwrap(); // restore
        fs::write(b_dir.join("img.png"), b"image-bytesX").unwrap();
        let h4 = compute_pack_sha256(&b_dir).unwrap();
        assert_ne!(h1, h4, "a byte change in an image must change the hash");

        // Add a new file → different hash.
        fs::write(b_dir.join("img.png"), b"image-bytes").unwrap(); // restore
        let h_restored = compute_pack_sha256(&b_dir).unwrap();
        assert_eq!(h1, h_restored, "restoring contents restores the hash");
        fs::write(b_dir.join("extra.txt"), b"new").unwrap();
        let h5 = compute_pack_sha256(&b_dir).unwrap();
        assert_ne!(h1, h5, "adding a file must change the hash");
    }

    // 5. diff_manifests: higher remote → copy; missing local → copy; equal →
    //    skip; LOWER remote → skip (never downgrade automatically).
    #[test]
    fn diff_manifests_rules() {
        let mut local = HashMap::new();
        local.insert("a".to_string(), 1u64);
        local.insert("b".to_string(), 2u64);
        local.insert("e".to_string(), 3u64); // local higher than remote → skip (no downgrade)
        let remote = ManifestBundle {
            bundle_version: "r".into(),
            packs: vec![
                ManifestPack {
                    pack_id: "a".into(),
                    version: 2,
                    sha256: "x".into(),
                    path: "p/a".into(),
                },
                ManifestPack {
                    pack_id: "b".into(),
                    version: 2,
                    sha256: "x".into(),
                    path: "p/b".into(),
                },
                ManifestPack {
                    pack_id: "c".into(),
                    version: 1,
                    sha256: "x".into(),
                    path: "p/c".into(),
                },
                ManifestPack {
                    pack_id: "e".into(),
                    version: 2,
                    sha256: "x".into(),
                    path: "p/e".into(),
                },
            ],
        };
        let to_copy = diff_manifests(&local, &remote);
        let ids: Vec<&str> = to_copy.iter().map(|p| p.pack_id.as_str()).collect();
        assert_eq!(
            ids,
            vec!["a", "c"],
            "a higher (copy), b equal (skip), c missing (copy), e lower (skip)"
        );
    }

    // 5b. A pack whose swap fails must NOT be recorded in the local manifest
    //     (else the next diff thinks it's installed and never retries it), and
    //     a skipped lower-version remote entry must not overwrite the local one.
    #[test]
    fn failed_swap_and_skipped_packs_not_recorded_in_manifest() {
        let content = TempDir::new().unwrap();
        let content_dir = content.path();
        let bundle = TempDir::new().unwrap();
        let bundle_root = bundle.path();

        // Installed: gamma v3.
        write_pack_files(
            &content_dir.join("g/gamma"),
            &[("pack.json", &pack_json("gamma", 3))],
        );
        write_manifest(content_dir, &build_manifest_for_dir(content_dir).unwrap()).unwrap();

        // Bundle: alpha v1 (installs), beta v1 (swap fails), gamma v2 (skipped).
        write_pack_files(
            &bundle_root.join("a/alpha"),
            &[("pack.json", &pack_json("alpha", 1))],
        );
        write_pack_files(
            &bundle_root.join("b/beta"),
            &[("pack.json", &pack_json("beta", 1))],
        );
        write_pack_files(
            &bundle_root.join("g/gamma"),
            &[("pack.json", &pack_json("gamma", 2))],
        );
        let key = make_key();
        build_and_sign_bundle(
            bundle_root,
            &key,
            &[
                ("alpha", 1, "a/alpha"),
                ("beta", 1, "b/beta"),
                ("gamma", 2, "g/gamma"),
            ],
        );
        // A plain FILE where beta's parent dir should be → rename into place fails.
        fs::write(content_dir.join("b"), b"not a dir").unwrap();

        let r = apply_update_bundle(content_dir, bundle_root, &key.pubkey_b64, "usb");

        assert!(r.applied.contains(&"alpha".to_string()), "{:?}", r.events);
        assert!(!r.applied.contains(&"beta".to_string()));
        let local = load_local_manifest(content_dir).expect("local manifest");
        let v = |id: &str| {
            local
                .packs
                .iter()
                .find(|p| p.pack_id == id)
                .map(|p| p.version)
        };
        assert_eq!(v("alpha"), Some(1));
        assert_eq!(v("beta"), None, "failed swap must not be recorded");
        assert_eq!(
            v("gamma"),
            Some(3),
            "skipped lower remote must not overwrite"
        );
    }

    // 6. Atomic copy on mid-copy failure. Pack A (v1) is installed; a bundle
    //    offers A (v2) + B (v1) where B's source contains a broken symlink that
    //    fails to read mid-copy. The apply must abort, leave NO half-written
    //    pack dir, and keep A at v1 byte-identical. (docs/plan/07 exit criterion:
    //    "A stick pulled mid-copy leaves the installed content intact.")
    #[cfg(unix)]
    #[test]
    fn mid_copy_failure_aborts_and_preserves_installed() {
        let content = TempDir::new().unwrap();
        let content_dir = content.path();
        let bundle = TempDir::new().unwrap();
        let bundle_root = bundle.path();

        // Installed: alpha v1.
        let alpha_v1_files: &[(&str, &[u8])] = &[
            ("pack.json", &pack_json("alpha", 1)),
            ("img.png", b"alpha-v1-image"),
        ];
        write_pack_files(&content_dir.join("packs/alpha"), alpha_v1_files);
        let seed_manifest = build_manifest_for_dir(content_dir).expect("seed manifest");
        write_manifest(content_dir, &seed_manifest).unwrap();
        let alpha_v1_bytes = fs::read(content_dir.join("packs/alpha/pack.json")).unwrap();

        // Bundle: alpha v2 (valid) + beta v1.
        write_pack_files(
            &bundle_root.join("packs/alpha"),
            &[
                ("pack.json", &pack_json("alpha", 2)),
                ("img.png", b"alpha-v2-image"),
            ],
        );
        write_pack_files(
            &bundle_root.join("packs/beta"),
            &[("pack.json", &pack_json("beta", 1)), ("good.json", b"good")],
        );
        let key = make_key();
        // build_and_sign computes beta's sha256 BEFORE we add the broken
        // symlink, so the manifest is internally consistent + correctly signed.
        build_and_sign_bundle(
            bundle_root,
            &key,
            &[("alpha", 2, "packs/alpha"), ("beta", 1, "packs/beta")],
        );

        // Now poison beta's source with a broken symlink — simulates a file that
        // becomes unreadable mid-copy (a yanked stick, a corrupt pack). copy_pack_dir
        // copies good.json OK, then fs::read on the broken symlink fails → abort.
        use std::os::unix::fs::symlink;
        symlink(
            "/nonexistent-tusome-test-target-xyz",
            bundle_root.join("packs/beta/broken"),
        )
        .unwrap();

        let r = apply_update_bundle(content_dir, bundle_root, &key.pubkey_b64, "usb");

        assert!(r.applied.is_empty(), "mid-copy failure must apply nothing");
        assert!(
            r.events
                .iter()
                .any(|e| e.outcome == "fail" && e.kind == "copy"),
            "expected a copy fail event, got: {:?}",
            r.events
        );
        // alpha is STILL v1, byte-identical.
        assert_eq!(
            fs::read(content_dir.join("packs/alpha/pack.json")).unwrap(),
            alpha_v1_bytes,
            "installed alpha must be unchanged"
        );
        assert_eq!(
            fs::read(content_dir.join("packs/alpha/img.png")).unwrap(),
            b"alpha-v1-image",
            "installed alpha image must be unchanged"
        );
        // beta was NOT installed.
        assert!(
            !content_dir.join("packs/beta").exists(),
            "no half-written beta dir"
        );
        // No stray staging dirs.
        assert!(
            no_staging_dirs(content_dir),
            "no .staging-* dirs should remain"
        );
        // Local manifest still reports alpha v1.
        let local = load_local_manifest(content_dir).expect("local manifest");
        let alpha = local.packs.iter().find(|p| p.pack_id == "alpha").unwrap();
        assert_eq!(alpha.version, 1, "local manifest still v1");
    }

    fn no_staging_dirs(content_dir: &Path) -> bool {
        let Ok(entries) = fs::read_dir(content_dir) else {
            return true;
        };
        for e in entries.flatten() {
            let name = e.file_name();
            let name = name.to_string_lossy();
            if name.starts_with(".staging-") || name.starts_with(".old-") {
                return false;
            }
        }
        true
    }
