// Tusome Phase 7 — Update core (docs/plan/07-updates-and-security.md).
//
// Two channels, one trust root:
//   * USB content updates   — a signed manifest.json on a stick; the manifest's
//                             detached minisign signature is the trust root. A
//                             checksum alone is NOT enough (a forged stick can
//                             recompute hashes); the signature is.
//   * Online content updates — a zip of the same bundle shape; the archive is
//                             untrusted, the manifest signature inside is the
//                             trust root.
//   * Online binary updates  — tauri-plugin-updater's check()/download_and_install().
//
// Content packs are PURE DATA (docs/plan/00-decisions.md §2): the apply path
// copies JSON + image files only. It never loads or executes anything from a
// bundle. Sim code ships in the signed binary, never in a content pack.
//
// The three runtime dirs stay separate (docs/plan/03-architecture.md): the
// content dir is the ONLY one this module writes to, resolved via
// app.path().app_data_dir() at call time — never a hardcoded path.
//
// ── Trust root ────────────────────────────────────────────────────────────
//
// `CONTENT_PUBKEY` is the base64 `RW…` line of the dev minisign public key
// generated by `cargo tauri signer generate -w ~/.tusome/tusome.key`. It is the
// SAME key whose full minisign text (base64-of-the-text blob) is embedded in
// tauri.conf.json `plugins.updater.pubkey` for the BINARY channel — one keypair
// serves both channels (docs/plan/07 §"Signing content bundles").
//
//   DEV KEY ONLY. The real production signing key + CI signing step is a
//   HUMAN/CI task (docs/plan/07). This dev key lets the pipeline build and sign
//   end-to-end now; rotating it to a production key before release is a config
//   line + a Rust const + a re-bundle, nothing more.
//
// DEVIATION NOTE: tauri.conf.json `pubkey` uses the base64-of-the-full-minisign-
// text blob (the .pub FILE content) because Tauri's updater base64-decodes the
// field then calls `minisign_verify::PublicKey::decode` on the result (which
// expects `untrusted comment: …\nRW…`). The Rust `CONTENT_PUBKEY` const here uses
// the bare `RW…` base64 line with `PublicKey::from_base64`, which needs no extra
// base64 dependency in the prod verify path. Both encode the IDENTICAL key.

