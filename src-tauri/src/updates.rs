        let key = make_key();
        build_and_sign_bundle(bundle_root, &key, &[("alpha", 2, "packs/alpha")]);

        let r = apply_update_bundle(content_dir, bundle_root, &key.pubkey_b64, "usb");

        assert_eq!(
            r.applied,
            vec!["alpha".to_string()],
            "alpha should be applied"
        );
        assert!(r.skipped.is_empty(), "nothing skipped");
        let fails: Vec<_> = r.events.iter().filter(|e| e.outcome == "fail").collect();
        assert!(fails.is_empty(), "no fail events, got: {:?}", r.events);
        // Content is actually installed.
