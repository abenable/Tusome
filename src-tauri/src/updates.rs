/// Scan every removable drive for a `tusome-updates/` bundle and apply it. Runs
/// silently at startup (spawned from `setup`, never blocks launch, never shows
/// the student anything) and on demand from the admin screen. Always returns;
/// never panics. Does NOT persist its events: the startup caller does, and the
/// webview caller appends the returned events via `append_update_log` (as it
/// does for every command here) — persisting in both places double-logged.
pub async fn run_usb_scan(app: &AppHandle) -> ApplyResult {
    let mut merged = ApplyResult::default();
    let Some(content_dir) = content_dir_for(app) else {
        merged.events.push(ev(
            "usb",
            "copy",
            "fail",
            "no content dir resolved".to_string(),
        ));
        return merged;
    };
    for root in scan_removable_roots() {
        let r = apply_update_bundle(&content_dir, &root, CONTENT_PUBKEY, "usb");
        merged.applied.extend(r.applied);
        merged.skipped.extend(r.skipped);
        merged.events.extend(r.events);
    }
    merged
}

#[tauri::command]
pub async fn scan_and_apply_usb_updates(app: AppHandle) -> ApplyResult {
    run_usb_scan(&app).await
}

/// Apply an online content bundle delivered as a zip. The archive is untrusted
/// (it came over HTTP); the manifest signature inside is the trust root. Never
/// panics.
#[tauri::command]
pub async fn apply_online_content_bundle(app: AppHandle, zip_bytes: Vec<u8>) -> ApplyResult {
    let mut result = ApplyResult::default();
    let Some(content_dir) = content_dir_for(&app) else {
        result.events.push(ev(
            "online",
            "extract",
            "fail",
            "no content dir resolved".to_string(),
        ));
        return result;
    };

    // Extract the untrusted archive into an OS-temp scratch dir (we only READ
    // from it; the atomic rename later is content_dir-staging -> content_dir,
    // same fs). `tempfile` is a dev-dep (tests only), so build the scratch dir
    // by hand and clean it up on scope exit.
    let scratch = match ScopedTempDir::new() {
        Ok(t) => t,
        Err(e) => {
            result.events.push(ev(
                "online",
                "extract",
                "fail",
                format!("create scratch dir: {e}"),
            ));
            return result;
        }
    };
    if let Err(e) = extract_zip(&zip_bytes, scratch.path()) {
        result
            .events
            .push(ev("online", "extract", "fail", format!("unzip: {e}")));
        return result;
    }

    apply_update_bundle(&content_dir, scratch.path(), CONTENT_PUBKEY, "online")
}

/// Check for a binary update and stage it, but never relaunch mid-lesson. Fails
/// silently on any network error. Never panics.
#[tauri::command]
pub async fn check_and_stage_app_update(app: AppHandle) -> AppUpdateResult {
    let current_version = app.package_info().version.to_string();
    let mut events: Vec<UpdateLogEvent> = Vec::new();
    let finish =
        |staged: bool, target: Option<String>, events: Vec<UpdateLogEvent>| -> AppUpdateResult {
            AppUpdateResult {
                staged,
                current_version,
                target_version: target,
                events,
            }
        };

    let updater = match tauri_plugin_updater::UpdaterExt::updater(&app) {
        Ok(u) => u,
        Err(e) => {
            events.push(ev("app", "check", "fail", format!("updater init: {e}")));
            return finish(false, None, events);
        }
    };
    let update = match updater.check().await {
        Ok(Some(u)) => u,
        Ok(None) => {
            events.push(ev("app", "check", "ok", "no update available".to_string()));
            return finish(false, None, events);
        }
        Err(e) => {
            // No network / no endpoint — fail silently, carry on offline.
            events.push(ev("app", "check", "fail", format!("check: {e}")));
            return finish(false, None, events);
        }
    };
    let target_version = update.version.clone();
    match update.download_and_install(|_n, _t| {}, || {}).await {
        Ok(()) => {
            events.push(ev(
                "app",
                "stage",
                "ok",
                "staged; will install on next launch".to_string(),
            ));
            finish(true, Some(target_version), events)
        }
        Err(e) => {
            events.push(ev(
                "app",
                "stage",
                "fail",
                format!("download_and_install: {e}"),
            ));
            finish(false, Some(target_version), events)
        }
    }
}

